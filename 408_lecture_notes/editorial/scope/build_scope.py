# Learning labels: identification, explanation, execution, transfer; several may apply.
REQ={'辨':'识记与辨析','理':'理解与解释','算':'计算与执行','综':'综合与迁移'}
chapters={}
rows=[]
def chapter(subject,num,title,source,depth,prereq,text):
    """Rows: stable ID | title | raw references | requirements | core method | conditions.
    Optional seventh field gives a more specific prerequisite.
    
    The raw reference may start with + for a necessary teaching prerequisite that
    is explicitly distinguished from a separately enumerated syllabus item.
    """
    ch=f'{subject}-{num:02d}'
    chapters[ch]={'科目':subject,'章号':num,'章名':title,'主资料定位':source,
                  '篇幅与深度依据':depth,'前置知识':prereq}
    for seq,line in enumerate(text.strip().splitlines(),1):
        cells=line.strip().split('|')
        assert len(cells) in (6,7),(ch,line)
        rowid,topic,refs,req,method,boundary=cells[:6]
        assert rowid.startswith(subject+'-'),rowid
        extra=refs.startswith('+')
        if extra: refs=refs[1:]
        rawcodes=[f'{subject}:{r}' for r in refs.split(';')]
        assert all(r in raw for r in rawcodes),(ch,rawcodes)
        pos=f'{SUBJECTS[subject][0]}第{num}章 §{num}.{seq}（规划）'
        if ch=='OS-03': pos=f'样章第3章 §3.{seq}（本轮正文位置待与实际成稿对齐）'
        basis='；'.join(f'本地转录副本PDF{raw[r]["本地PDF页"]}页 {r.split(":",1)[1]}' for r in rawcodes)
        if extra: basis='必要教学前置，服务于 '+basis+'；不是副本独立列项'
        rows.append({'知识点 ID':rowid,'知识点':topic,'大纲依据':basis,
          '前置知识':cells[6] if len(cells)==7 else prereq,
          '学习要求':'；'.join(REQ[x] for x in req),'正文位置':pos,'核心考法':method,
          '例题 ID':'待选；不据目录推定已核验题目','重要条件与边界':boundary,
          '内容与题目来源':f'WD27-{subject} {source}（仅目录定位已读；正文待逐章核验）；题目待选源与复算',
          '核验状态':'初稿：本地转录条目已图读；2027正式细目待逐条核；正文/题目待验',
          '科目':SUBJECTS[subject][0],'原条目编号':rawcodes,'规划章ID':ch,'规划节号':f'{num}.{seq}',
          '覆盖性质':'必要教学前置' if extra else '本地大纲细目规划',
          '教学优先级依据':'大纲转录条目、前置支撑与易混边界；不表示题库频率'})

